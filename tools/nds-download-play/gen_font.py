"""Renders the client's text from the app's MiSans into two glyph atlases plus metrics, as C.

The bottom screen draws with the DS's 3D engine, which the emulator renders at its 3D resolution: its glyphs are drawn at
SCALE times their size on screen, in the A5I3 texture format (5-bit alpha, one white palette entry). The top screen is a
2D bitmap at the DS's own resolution: its glyphs are 8-bit alpha at 1x.

The app's build fetches MiSans (shared/build.gradle.kts, fetchMiSans); the font may be embedded in software but not
shipped on its own, so the generated table stays out of the repository and only the built client carries it.

Usage: gen_font.py <regular.ttf> <semibold.ttf> <out.c>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SCALE = 2
regular, semibold, out = sys.argv[1], sys.argv[2], sys.argv[3]
# (C name, file, size on screen in DS pixels)
FACES_3D = [("font3d_small", regular, 11), ("font3d_body", regular, 13), ("font3d_title", semibold, 15)]
FACES_2D = [("font2d_small", regular, 11), ("font2d_body", regular, 13), ("font2d_title", semibold, 15),
            ("font2d_big", semibold, 20)]
TEXTURE_BYTES_MAX = 256 * 1024  # VRAM banks A and B


def pack(faces, scale, width, extra=None):
    """Glyphs of [faces] at [scale] packed in rows [width] wide; [extra] (an image) after them."""
    pen_x, pen_y, row_h = 0, 0, 0
    placed = []
    for name, path, size in faces:
        font = ImageFont.truetype(path, size * scale)
        for code in range(32, 127):
            left, top, right, bottom = font.getbbox(chr(code))
            w, h = max(0, right - left), max(0, bottom - top)
            img = None
            pos = (0, 0)
            if w and h:
                img = Image.new("L", (w + 2, h + 2), 0)  # a pixel of margin so filtering never bleeds a neighbour in
                ImageDraw.Draw(img).text((1 - left, 1 - top), chr(code), font=font, fill=255)
                if pen_x + img.width > width:
                    pen_x, pen_y, row_h = 0, pen_y + row_h, 0
                pos = (pen_x, pen_y)
                pen_x += img.width
                row_h = max(row_h, img.height)
            placed.append((name, img, pos, left - 1, top - 1, round(font.getlength(chr(code))), font.getmetrics()))
    extra_pos = None
    if extra is not None:
        if pen_x + extra.width + 2 > width:
            pen_x, pen_y, row_h = 0, pen_y + row_h, 0
        extra_pos = (pen_x + 1, pen_y + 1)
        row_h = max(row_h, extra.height + 2)
    height = 8
    while height < pen_y + row_h:
        height *= 2
    atlas = Image.new("L", (width, height), 0)
    for _, img, pos, *_ in placed:
        if img:
            atlas.paste(img, pos)
    if extra is not None:
        atlas.paste(extra, extra_pos)
    return atlas, placed, extra_pos


def tables(lines, faces, placed, scale):
    for name, _, _ in faces:
        glyphs = [g for g in placed if g[0] == name]
        ascent, descent = glyphs[0][6]
        entries = []
        for _, img, (x, y), left, top, advance, _ in glyphs:
            w, h = (img.width, img.height) if img else (0, 0)
            entries.append(f"{{{x}, {y}, {w}, {h}, {left}, {top}, {advance}}}")
        lines.append(f"static const Glyph {name}_glyphs[95] = {{{', '.join(entries)}}};")
        lines.append(f"const Font {name} = {{{name}_glyphs, {scale}, {round((ascent + descent) / scale)}, "
                     f"{round(ascent / scale)}}};")
        lines.append("")


# A smooth white disc for round corners, drawn 4x over and scaled down for clean edges.
DISC = 32 * SCALE
big = Image.new("L", (DISC * 4, DISC * 4), 0)
ImageDraw.Draw(big).ellipse((0, 0, DISC * 4 - 1, DISC * 4 - 1), fill=255)
disc = big.resize((DISC, DISC), Image.LANCZOS)

atlas3d, placed3d, disc_pos = pack(FACES_3D, SCALE, 1024, disc)
assert atlas3d.width * atlas3d.height <= TEXTURE_BYTES_MAX, f"3D atlas {atlas3d.size} is over VRAM A+B"
atlas2d, placed2d, _ = pack(FACES_2D, 1, 512)
# A5I3: alpha in the top five bits, palette entry 0 (white) below.
a5i3 = bytes((a >> 3) << 3 for a in atlas3d.tobytes())

lines = ['// Generated by gen_font.py from MiSans: do not edit.', '#include "font.h"', '',
         f'const u16 font3d_w = {atlas3d.width}, font3d_h = {atlas3d.height};',
         f'const u16 disc_x = {disc_pos[0]}, disc_y = {disc_pos[1]}, disc_d = {DISC};',
         f'const u8 font3d_atlas[] __attribute__((aligned(4))) = {{{",".join(str(b) for b in a5i3)}}};',
         f'const u16 font2d_w = {atlas2d.width}, font2d_h = {atlas2d.height};',
         f'const u8 font2d_atlas[] = {{{",".join(str(b) for b in atlas2d.tobytes())}}};', '']
tables(lines, FACES_3D, placed3d, SCALE)
tables(lines, FACES_2D, placed2d, 1)
open(out, "w").write("\n".join(lines))
print(f"3D atlas {atlas3d.size}, 2D atlas {atlas2d.size}")
