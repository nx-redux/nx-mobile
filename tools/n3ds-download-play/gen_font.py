"""Renders the client's text sizes from the app's MiSans into one glyph atlas (8-bit alpha) plus metrics, as C.

Glyphs are drawn at SCALE times their size on screen: the client draws them with the GPU at 1/SCALE, and the emulator
renders GPU drawing at its 3D resolution, so text stays sharp on a phone's screen.

The app's build fetches MiSans (shared/build.gradle.kts, fetchMiSans); the font may be embedded in software but not
shipped on its own, so the generated table stays out of the repository and only the built client carries it.

Usage: gen_font.py <regular.ttf> <semibold.ttf> <out.c>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SCALE = 3
ATLAS_W = 1024
regular, semibold, out = sys.argv[1], sys.argv[2], sys.argv[3]
# (C name, file, size on screen in 3DS pixels)
FACES = [("font_small", regular, 13), ("font_body", regular, 15), ("font_title", semibold, 17), ("font_big", semibold, 22)]

pen_x, pen_y, row_h = 0, 0, 0
placed = []  # (face, code, image, left, top, advance) with atlas position filled in below
for name, path, size in FACES:
    font = ImageFont.truetype(path, size * SCALE)
    for code in range(32, 127):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        w, h = max(0, right - left), max(0, bottom - top)
        img = None
        if w and h:
            img = Image.new("L", (w + 2, h + 2), 0)  # a pixel of margin so filtering never bleeds a neighbour in
            ImageDraw.Draw(img).text((1 - left, 1 - top), ch, font=font, fill=255)
            if pen_x + img.width > ATLAS_W:
                pen_x, pen_y, row_h = 0, pen_y + row_h, 0
            pos = (pen_x, pen_y)
            pen_x += img.width
            row_h = max(row_h, img.height)
        else:
            pos = (0, 0)
        placed.append((name, code, img, pos, left - 1, top - 1, round(font.getlength(ch)), font.getmetrics()))

# A smooth white disc for round corners, drawn 4x over and scaled down for clean edges.
DISC = 32 * SCALE
big = Image.new("L", (DISC * 4, DISC * 4), 0)
ImageDraw.Draw(big).ellipse((0, 0, DISC * 4 - 1, DISC * 4 - 1), fill=255)
disc = big.resize((DISC, DISC), Image.LANCZOS)
if pen_x + DISC + 2 > ATLAS_W:
    pen_x, pen_y, row_h = 0, pen_y + row_h, 0
disc_pos = (pen_x + 1, pen_y + 1)
row_h = max(row_h, DISC + 2)

height = 8
while height < pen_y + row_h:
    height *= 2
atlas = Image.new("L", (ATLAS_W, height), 0)
for _, _, img, pos, *_ in placed:
    if img:
        atlas.paste(img, pos)
atlas.paste(disc, disc_pos)

lines = ['// Generated by gen_font.py from MiSans: do not edit.', '#include "font.h"', '',
         f'const u16 font_atlas_w = {ATLAS_W}, font_atlas_h = {height};',
         f'const u16 disc_x = {disc_pos[0]}, disc_y = {disc_pos[1]}, disc_d = {DISC};',
         f'const u8 font_atlas[] = {{{",".join(str(b) for b in atlas.tobytes())}}};', '']
for name, _, _ in [(f[0], f[1], f[2]) for f in FACES]:
    glyphs = [g for g in placed if g[0] == name]
    ascent, descent = glyphs[0][7]
    entries = []
    for _, code, img, (x, y), left, top, advance, _ in glyphs:
        w, h = (img.width, img.height) if img else (0, 0)
        entries.append(f"{{{x}, {y}, {w}, {h}, {left}, {top}, {advance}}}")
    lines.append(f"static const Glyph {name}_glyphs[95] = {{{', '.join(entries)}}};")
    lines.append(f"const Font {name} = {{{name}_glyphs, {(ascent + descent) / SCALE:.2f}f, {ascent / SCALE:.2f}f}};")
    lines.append("")
open(out, "w").write("\n".join(lines))
