"""Renders the client's text sizes from the app's MiSans into a C table of 8-bit alpha glyphs (ASCII 32-126).

The app's build fetches MiSans (shared/build.gradle.kts, fetchMiSans); the font may be embedded in software but not
shipped on its own, so the generated table stays out of the repository and only the built client carries it.

Usage: gen_font.py <regular.ttf> <semibold.ttf> <out.c>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

regular, semibold, out = sys.argv[1], sys.argv[2], sys.argv[3]
# (C name, file, pixel size)
FACES = [("font_small", regular, 13), ("font_body", regular, 15), ("font_title", semibold, 17), ("font_big", semibold, 22)]

lines = ['// Generated by gen_font.py from MiSans: do not edit.', '#include "font.h"', '']
for name, path, size in FACES:
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], []
    for code in range(32, 127):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        w, h = max(0, right - left), max(0, bottom - top)
        advance = round(font.getlength(ch))
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
            data.extend(img.tobytes())
        glyphs.append(f"{{{offset}, {w}, {h}, {left}, {top}, {advance}}}")
    lines.append(f"static const u8 {name}_data[] = {{{', '.join(str(b) for b in data) or '0'}}};")
    lines.append(f"static const Glyph {name}_glyphs[95] = {{{', '.join(glyphs)}}};")
    lines.append(f"const Font {name} = {{{name}_glyphs, {name}_data, {ascent + descent}, {ascent}}};")
    lines.append("")
open(out, "w").write("\n".join(lines))
